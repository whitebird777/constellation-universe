/**
 * 从题库随机抽取 n 道题（不重复）
 * @param {number} n - 需要抽取的题目数量
 * @returns {Array} 随机题目数组
 */
function pickRandom(n) {
  var pool = QUESTIONS.slice();
  var result = [];
  n = Math.min(n, pool.length);
  for (var i = 0; i < n; i++) {
    var idx = Math.floor(Math.random() * pool.length);
    result.push(pool[idx]);
    pool.splice(idx, 1);
  }
  return result;
}

